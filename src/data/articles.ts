export type ArticleBlock =
  | { type: 'p'; text: string }
  | { type: 'steps'; items: string[] }
  | { type: 'list'; items: string[] }
  | { type: 'table'; head: string[]; rows: string[][] }
  | { type: 'note'; text: string };

export interface ArticleSection {
  id: string;
  title: string;
  blocks: ArticleBlock[];
}

export interface Article {
  slug: string;
  title: string;        // <title>
  description: string;  // meta description
  h1: string;
  lead: string;
  published: string;    // YYYY-MM-DD
  readTime: string;
  category: string;
  sections: ArticleSection[];
  faq: { question: string; answer: string }[];
  cta: { title: string; text: string };
}

const LINK_RE = /\[([^\]]+)\]\(([^)]+)\)/g;

/** Все ссылки статьи — из вступления, разделов, FAQ и CTA. */
export function articleLinks(a: Article): string[] {
  const texts: string[] = [a.lead, a.cta.text];
  for (const s of a.sections) {
    for (const b of s.blocks) {
      if (b.type === 'p' || b.type === 'note') texts.push(b.text);
      else if (b.type === 'steps' || b.type === 'list') texts.push(...b.items);
      else texts.push(...b.head, ...b.rows.flat());
    }
  }
  for (const f of a.faq) texts.push(f.answer);
  const out: string[] = [];
  for (const t of texts) for (const m of t.matchAll(LINK_RE)) out.push(m[2]);
  return out;
}

