#!/usr/bin/env node
/**
 * GST-61 — Turn raw Avito listings into avito_listing seed rows.
 *
 * Reads:
 *   public/data/avito-prices.json    — aggregate stats (source of model_key, via build-signals.mjs)
 *   public/data/avito-listings.json  — raw lots {model_name, processor, ram, ssd, price, url, title, seen_at}
 *                                       written by scripts/avito-parser/parser.py
 *
 * Each listing is joined to the engine's model_key using buildModelKeyMap() — the
 * SAME code that builds signal keys — so a lot lands on exactly the model whose
 * signal it belongs to. Listings whose config never seeds a signal (catch-all,
 * F1, <MIN_SAMPLE) find no key and are dropped. Emits an idempotent upsert on the
 * natural key (url): re-seeing an ad refreshes its price + seen_at, keeps first_seen_at.
 *
 * The listing feed (view sourcing_listing_feed) does the economics + freshness
 * filtering; this builder only persists the raw truth.
 *
 * Usage:
 *   node scripts/sourcing/build-listings.mjs --sql   > listings.sql   # upsert SQL for review / apply
 *   node scripts/sourcing/build-listings.mjs --json                   # matched rows as JSON (inspection)
 */

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { buildModelKeyMap, configKey } from './build-signals.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PRICES_PATH = resolve(__dirname, '../../public/data/avito-prices.json');
const LISTINGS_PATH = resolve(__dirname, '../../public/data/avito-listings.json');

function loadJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

// "2026-08-15 22:41" (parser format) -> ISO the DB accepts; falls back to as-is.
function normalizeTs(ts) {
  if (!ts) return null;
  const s = String(ts).trim();
  return /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}/.test(s) ? s.replace(' ', 'T') : s;
}

function buildRows() {
  const prices = loadJson(PRICES_PATH);
  const stats = Array.isArray(prices.stats) ? prices.stats : [];
  const keyMap = buildModelKeyMap(stats);

  const listingsRaw = loadJson(LISTINGS_PATH);
  const listings = Array.isArray(listingsRaw.listings) ? listingsRaw.listings : [];
  const fallbackSeen = normalizeTs(listingsRaw.generated_at);

  const rows = [];
  const byUrl = new Map(); // dedup by url — last wins
  let unmatched = 0;
  for (const l of listings) {
    const url = String(l.url || '').trim();
    const price = Number(l.price) || 0;
    if (!url || price <= 0) continue;
    const modelKey = keyMap.get(configKey(l));
    if (!modelKey) { unmatched++; continue; } // config never seeds a signal
    byUrl.set(url, {
      model_key: modelKey,
      url,
      price_rub: Math.round(price),
      title: l.title ? String(l.title).slice(0, 200) : null,
      seen_at: normalizeTs(l.seen_at) || fallbackSeen,
    });
  }
  for (const r of byUrl.values()) rows.push(r);
  rows.sort((a, b) => (a.model_key < b.model_key ? -1 : a.model_key > b.model_key ? 1 : a.price_rub - b.price_rub));
  return { rows, unmatched, total: listings.length };
}

function sqlVal(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

function emitSql(rows) {
  let out = '-- GST-61 avito_listing seed (generated by scripts/sourcing/build-listings.mjs)\n';
  if (!rows.length) return out + '-- (no matched listings)\n';
  out += 'begin;\n';
  out += 'insert into public.avito_listing (model_key, url, price_rub, title, seen_at) values\n';
  out += rows
    .map((r) => `  (${sqlVal(r.model_key)}, ${sqlVal(r.url)}, ${sqlVal(r.price_rub)}, ${sqlVal(r.title)}, ${sqlVal(r.seen_at)}::timestamptz)`)
    .join(',\n');
  // Re-seeing an ad refreshes price + seen_at; first_seen_at is preserved.
  out += '\non conflict (url) do update set';
  out += ' model_key=excluded.model_key, price_rub=excluded.price_rub, title=excluded.title, seen_at=excluded.seen_at;\n';
  out += 'commit;\n';
  return out;
}

function main() {
  const mode = process.argv.includes('--json') ? 'json' : 'sql';
  const { rows, unmatched, total } = buildRows();
  if (mode === 'json') {
    process.stdout.write(JSON.stringify({ total, matched: rows.length, unmatched, rows }, null, 2));
    return;
  }
  process.stderr.write(`build-listings: ${rows.length} matched / ${total} total (${unmatched} unmatched)\n`);
  process.stdout.write(emitSql(rows));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  main();
}

export { buildRows, emitSql };
